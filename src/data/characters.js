export function getCharacter(id) {
  return characters.find(c => c.id === id) || characters[0];
}

export function getCharacterIndex(id) {
  return characters.findIndex(c => c.id === id) || 0;
}

export function roleInfo(role) {
  return ROLES[role] || ROLES.assault;
}

export function characterInitials(character) {
  const name = character.name.replace(/[^A-Z]/g, '');
  return name.slice(0, 2) || 'VC';
}
