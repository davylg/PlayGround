export function getWeapon(id) {
  return weapons[id] || weapons.rifle;
}

export function weaponStatsForUI(id) {
  const w = getWeapon(id);
  return {
    name: w.name,
    type: w.type,
    damage: w.damage,
    fireRate: Math.round(60 / w.fireRate),
    magazine: w.magazineSize,
    range: Math.round(w.range * 10),
    accuracy: Math.max(4, Math.min(100, Math.round(100 - w.spread * 1400))),
  };
}
